def render(config, check_environment=True, allow_downloads=True):
    lines = ['[analysis]', 'folder = ' + config['analysis_dir']]
    for role in ('tumor', 'normal'):
        rows = [row for row in config['samples'] if row['role'] == role]
        lines += ['', '[' + role + ']', 'sample = ' + rows[0]['sample'], 'r1 =']
        lines += ['    ' + row['fastq_1'] for row in rows]
        lines += ['r2 ='] + ['    ' + row['fastq_2'] for row in rows]
    ref, trim = config['reference'], config['trimming']
    lines += ['', '[reference]', 'fasta = ' + ref['fasta'], 'assembly = ' + ref['assembly'], 'known_sites =']
    lines += ['    ' + item for item in ref['known_sites']]
    lines += ['vep_cache = ' + ref['vep_cache_dir'], 'vep_cache_version = 113', '', '[trimming]',
              'adapters = ' + trim['adapter_mode'], 'adapter_r1 = ' + (trim['adapter_r1'] or ''),
              'adapter_r2 = ' + (trim['adapter_r2'] or ''), 'quality = ' + str(trim['quality']),
              'min_read_length = ' + str(trim['min_read_length'])]
    for section, (stage, mapping) in fixed.RESOURCE_SECTIONS.items():
        values = config['resources'][stage]
        lines += ['', '[' + section + ']']
        for external, internal in mapping.items():
            lines += ['{} = {}'.format(external, values[internal])]
        if section in ('alignment', 'calling'):
            lines += ['gpus = ' + ','.join(map(str, values['gpu_devices']))]
        if section == 'bqsr':
            lines += ['gpu = ' + str(values['gpu_devices'][0])]
    lines += ['', '[runtime]', 'java = /selected/java', 'nextflow = /selected/nextflow',
              'check_environment = ' + str(check_environment), 'allow_downloads = ' + str(allow_downloads)]
    return '\n'.join(lines) + '\n'


class FixedSettingsTests(unittest.TestCase):
    def setUp(self):
        self.fixture = fixture_module.ConfigurationTests()
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        self.config = copy.deepcopy(self.fixture.config)
        # These are generated by the fixed interface, not entered by the user.
        for row in self.config['samples']:
            row['pair_id'] = row['sample'] + '_pair1'
        self.ini = self.fixture.base / 'settings.ini'
        self.ini.write_text(render(self.config))
        self.transcript = io.StringIO()

    def run_main(self, *flags, confirm=True, subprocess_code=0, tty=True):
        with contextlib.redirect_stdout(self.transcript), contextlib.redirect_stderr(self.transcript), \
                mock.patch.object(sys.stdin, 'isatty', return_value=tty), \
                mock.patch.object(cfg, 'yes_no', return_value=confirm) as ask, \
                mock.patch.object(subprocess, 'run', return_value=mock.Mock(returncode=subprocess_code)) as run:
            code = fixed.main([str(self.ini), *flags])
        return code, ask, run

    def test_parse_and_validate_round_trip_without_pair_id_fields(self):
        raw, runtime = fixed.parse_settings(self.ini)
        validated = cfg.validate_configuration(raw)
        self.assertEqual(validated, self.config)
        self.assertEqual([row['pair_id'] for row in raw['samples']], ['TUMOR_pair1', 'NORMAL_pair1'])
        self.assertTrue(runtime['check_environment'])
        self.assertTrue(runtime['allow_downloads'])

    def test_multiple_lanes_auto_count_and_identifiers(self):
        for number in range(2, 5):
            r1, r2 = self.fixture.base / ('lane{}_R1.fastq.gz'.format(number)), self.fixture.base / ('lane{}_R2.fastq.gz'.format(number))
            r1.write_bytes(b'fixture\n')
            r2.write_bytes(b'fixture\n')
            self.config['samples'].append({'sample': 'TUMOR', 'role': 'tumor', 'pair_id': 'irrelevant',
                                          'fastq_1': str(r1), 'fastq_2': str(r2)})
        self.ini.write_text(render(self.config))
        raw, _ = fixed.parse_settings(self.ini)
        validated = cfg.validate_configuration(raw)
        tumor = [row for row in validated['samples'] if row['role'] == 'tumor']
        self.assertEqual(len(tumor), 4)
        self.assertEqual([row['pair_id'] for row in tumor], ['TUMOR_pair1', 'TUMOR_pair2', 'TUMOR_pair3', 'TUMOR_pair4'])

    def test_different_r1_r2_counts_rejected(self):
        content = self.ini.read_text().replace('r1 =\n', 'r1 =\n    /extra/R1.fastq.gz\n', 1)
        self.ini.write_text(content)
        with self.assertRaisesRegex(ValueError, 'R1/R2 counts differ'):
            fixed.parse_settings(self.ini)

    def test_duplicate_files_detected_by_shared_validator(self):
        self.ini.write_text(self.ini.read_text().replace(self.config['samples'][0]['fastq_2'], self.config['samples'][0]['fastq_1']))
        code, ask, run = self.run_main('--check')
        self.assertEqual(code, 1)
        ask.assert_not_called()
        run.assert_not_called()
        self.assertFalse(self.fixture.output.exists())

    def test_unknown_key_or_section_rejected(self):
        content = self.ini.read_text()
        for bad in (content.replace('bwa_thread_pool', 'bwa_pool'), content + '\n[unexpected]\nx = 1\n'):
            self.ini.write_text(bad)
            with self.assertRaisesRegex(ValueError, 'Unknown'):
                fixed.parse_settings(self.ini)

    def test_duplicate_ini_options_rejected(self):
        self.ini.write_text(self.ini.read_text().replace('sample = TUMOR', 'sample = TUMOR\nsample = SECOND'))
        code, ask, run = self.run_main('--check')
        self.assertEqual(code, 1)
        ask.assert_not_called()
        run.assert_not_called()

    def test_quotes_comments_and_gpu_whitespace_are_supported(self):
        content = self.ini.read_text().replace('gpus = 7,6,5', 'gpus = 7, 6, 5 # selected GPUs')
        content = content.replace('fasta = ' + self.config['reference']['fasta'], 'fasta = "' + self.config['reference']['fasta'] + '"')
        for site in self.config['reference']['known_sites']:
            content = content.replace(site, '"' + site + '"')
        self.ini.write_text(content)
        raw, _ = fixed.parse_settings(self.ini)
        self.assertEqual(cfg.validate_configuration(raw), self.config)

    def test_custom_adapters_quality_and_resources(self):
        self.config['trimming'].update(adapter_mode='custom', adapter_r1='ACGT', adapter_r2='TAGC', quality=25, min_read_length=35)
        self.config['resources']['alignment'].update(cpus=32, sorting_memory_gb=64)
        self.ini.write_text(render(self.config))
        raw, _ = fixed.parse_settings(self.ini)
        validated = cfg.validate_configuration(raw)
        self.assertEqual(validated, self.config)
        self.assertEqual(validated['resources']['alignment']['bwa_thread_pool'], 16)

    def test_custom_adapters_require_both_sequences(self):
        self.ini.write_text(self.ini.read_text().replace('adapters = auto', 'adapters = custom'))
        with self.assertRaisesRegex(ValueError, 'require both'):
            fixed.parse_settings(self.ini)

    def test_run_is_explicitly_dispatched_only_after_storage_confirmation(self):
        helper = mock.Mock()
        helper.execute.return_value = 9
        with mock.patch.dict(sys.modules, {'execute_analysis': helper}):
            code, ask, run = self.run_main('--run')
        self.assertEqual(code, 9)
        ask.assert_called_once()
        run.assert_not_called()
        self.assertEqual(helper.execute.call_args.args[0], self.config)

    def test_run_cannot_disable_preflight(self):
        self.ini.write_text(render(self.config, check_environment=False))
        code, ask, run = self.run_main('--run')
        self.assertEqual(code, 1)
        ask.assert_not_called()
        run.assert_not_called()

    def test_check_has_no_questions_writes_or_commands(self):
        before = {p: (p.stat().st_size, p.stat().st_mtime_ns) for p in self.fixture.base.rglob('*') if p.is_file()}
        code, ask, run = self.run_main('--check', tty=False)
        self.assertEqual(code, 0, self.transcript.getvalue())
        ask.assert_not_called()
        run.assert_not_called()
        self.assertFalse(self.fixture.output.exists())
        self.assertEqual(before, {p: (p.stat().st_size, p.stat().st_mtime_ns) for p in self.fixture.base.rglob('*') if p.is_file()})

    def test_cancel_creates_nothing(self):
        code, ask, run = self.run_main(confirm=False)
        self.assertEqual(code, 0, self.transcript.getvalue())
        ask.assert_called_once()
        run.assert_not_called()
        self.assertFalse(self.fixture.output.exists())

    def test_prepare_only_saves_real_metadata_files_without_environment_checks(self):
        code, ask, run = self.run_main('--prepare-only')
        self.assertEqual(code, 0, self.transcript.getvalue())
        ask.assert_called_once()
        run.assert_not_called()
        files = list(self.fixture.output.rglob('*'))
        self.assertTrue(all(not p.is_symlink() for p in files))
        saved = json.loads((self.fixture.output / 'brisance.json').read_text())
        self.assertEqual(saved, self.config)
        self.assertEqual(list((self.fixture.output / 'work').iterdir()), [])
        self.assertEqual(list((self.fixture.output / 'results').iterdir()), [])
        archived = list((self.fixture.output / 'reports').glob('settings-*/settings.ini'))
        self.assertEqual(len(archived), 1)
        self.assertEqual(archived[0].read_bytes(), self.ini.read_bytes())

    def test_runtime_executable_paths_forwarded_and_failure_propagated(self):
        code, ask, run = self.run_main(subprocess_code=7)
        self.assertEqual(code, 7)
        ask.assert_called_once()
        command = run.call_args.args[0]
        self.assertIn('/selected/java', command)
        self.assertIn('/selected/nextflow', command)
        self.assertIn(str(self.fixture.output / 'brisance.json'), command)
        self.assertNotIn('--no-download', command)

    def test_no_download_policy_and_override(self):
        self.ini.write_text(render(self.config, allow_downloads=False))
        code, _, run = self.run_main()
        self.assertEqual(code, 0)
        self.assertIn('--no-download', run.call_args.args[0])
        self.ini.write_text(render(self.config, allow_downloads=True))
        code, _, run = self.run_main('--no-download')
        self.assertEqual(code, 0)
        self.assertIn('--no-download', run.call_args.args[0])

    def test_same_settings_can_repeat_checks_without_overwriting_configuration(self):
        self.assertEqual(self.run_main('--prepare-only')[0], 0)
        config_path = self.fixture.output / 'brisance.json'
        before = config_path.stat().st_mtime_ns
        self.assertEqual(self.run_main('--prepare-only')[0], 0)
        self.assertEqual(config_path.stat().st_mtime_ns, before)
        self.assertEqual(len(list((self.fixture.output / 'reports').glob('settings-*/settings.ini'))), 2)

    def test_existing_different_settings_are_not_overwritten(self):
        self.assertEqual(self.run_main('--prepare-only')[0], 0)
        original = (self.fixture.output / 'brisance.json').read_bytes()
        self.ini.write_text(self.ini.read_text().replace('quality = 20', 'quality = 25'))
        code, ask, run = self.run_main()
        self.assertEqual(code, 1)
        ask.assert_not_called()
        run.assert_not_called()
        self.assertEqual((self.fixture.output / 'brisance.json').read_bytes(), original)

    def test_modified_source_after_summary_is_not_saved_under_old_summary(self):
        def modify(*args, **kwargs):
            self.ini.write_text(self.ini.read_text().replace('quality = 20', 'quality = 25'))
            return True
        with contextlib.redirect_stdout(self.transcript), contextlib.redirect_stderr(self.transcript), \
                mock.patch.object(sys.stdin, 'isatty', return_value=True), mock.patch.object(cfg, 'yes_no', side_effect=modify), \
                mock.patch.object(subprocess, 'run') as run:
            code = fixed.main([str(self.ini)])
        self.assertEqual(code, 1)
        run.assert_not_called()
        self.assertFalse(self.fixture.output.exists())
        self.assertIn('changed after the summary', self.transcript.getvalue())

    def test_noninteractive_execution_fails_before_save(self):
        code, ask, run = self.run_main(tty=False)
        self.assertEqual(code, 1)
        ask.assert_not_called()
        run.assert_not_called()
        self.assertFalse(self.fixture.output.exists())

    def test_existing_unrecognized_folder_and_symlink_are_refused(self):
        self.fixture.output.mkdir()
        code, ask, run = self.run_main('--check')
        self.assertEqual(code, 1)
        ask.assert_not_called()
        run.assert_not_called()
        other = self.fixture.base / 'link'
        other.symlink_to(self.fixture.output, target_is_directory=True)
        self.ini.write_text(self.ini.read_text().replace(str(self.fixture.output), str(other)))
        code, _, _ = self.run_main('--check')
        self.assertEqual(code, 1)
        self.assertIn('symlink', self.transcript.getvalue())

    def test_invalid_boolean_and_shell_text_are_not_executed(self):
        self.ini.write_text(self.ini.read_text().replace('allow_downloads = True', 'allow_downloads = maybe'))
        with self.assertRaisesRegex(ValueError, 'true or false'):
            fixed.parse_settings(self.ini)
        marker = self.fixture.base / 'not-created'
        content = render(self.config).replace(self.config['samples'][0]['fastq_1'], '$(touch {})'.format(marker))
        self.ini.write_text(content)
        code, ask, run = self.run_main('--check')
        self.assertEqual(code, 1)
        ask.assert_not_called()
        run.assert_not_called()
        self.assertFalse(marker.exists())

    def test_template_parse_and_shell_entrypoint_syntax(self):
        raw, runtime = fixed.parse_settings(ROOT / 'interface/brisance.example.ini')
        self.assertEqual(len(raw['samples']), 2)
        self.assertTrue(runtime['allow_downloads'])
        self.assertEqual(len(raw['reference']['known_sites']), 3)
        result = subprocess.run(['bash', '-n', str(ROOT / 'interface/run_brisance.sh')], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        result = subprocess.run(['bash', str(ROOT / 'interface/run_brisance.sh'), '--help'], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('--check', result.stdout)

    def test_turing_settings_match_all_ten_recorded_input_names(self):
        path = ROOT / 'interface/hg008-turing.local.ini'
        if not path.exists():
            self.skipTest('Turing-specific local settings are not distributed in Git.')
        raw, runtime = fixed.parse_settings(path)
        with (ROOT / 'validation/hg008_100pct/input_files.csv').open() as handle:
            records = list(csv.DictReader(handle))
        expected = {Path(row['relative_path']).name for row in records}
        found = [Path(row[key]).name for row in raw['samples'] for key in ('fastq_1', 'fastq_2')]
        self.assertEqual(len(found), 10)
        self.assertEqual(len(set(found)), 10)
        self.assertEqual(set(found), expected)
        self.assertEqual(sum(row['role'] == 'tumor' for row in raw['samples']), 4)
        for row in raw['samples']:
            self.assertEqual(Path(row['fastq_1']).name.replace('_R1_', '_R2_'), Path(row['fastq_2']).name)
        self.assertFalse(runtime['allow_downloads'])

    def test_small_preset_uses_only_two_tiny_pairs_and_separate_destination(self):
        path = ROOT / 'interface/hg008-small-turing.local.ini'
        if not path.exists():
            self.skipTest('Turing-specific personal settings are not distributed in Git.')
        raw, runtime = fixed.parse_settings(path)
        self.assertEqual(len(raw['samples']), 2)
        self.assertTrue(raw['analysis_dir'].endswith('/analysis-small-test-01'))
        for row in raw['samples']:
            for key in ('fastq_1', 'fastq_2'):
                self.assertIn('/data/test/trim-test-oaq6d_co/', row[key])
                self.assertNotIn('/data/raw/', row[key])
        self.assertTrue(runtime['check_environment'])
        self.assertFalse(runtime['allow_downloads'])


